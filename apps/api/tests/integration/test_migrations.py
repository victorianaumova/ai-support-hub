"""Alembic migrations: they run from an empty database, back down to nothing and up again, and
autogenerate finds no difference to the SQLAlchemy models. Autogenerate does not compare CHECK
constraints; the enum CHECKs are compared in test_schema_checks.py."""

from collections.abc import Iterator

import psycopg
import pytest
from alembic import command
from psycopg import sql

from hub.observability.readiness import libpq_url

from ._db import alembic_config, as_user, migrate

TABLES = {
    "customers",
    "operators",
    "tickets",
    "messages",
    "settings",
    "feedback",
    "audit_log",
    "llm_calls",
    "runs",
    "drafts",
    "kb_documents",
    "kb_chunks",
    "customer_memory",
    "tool_calls",
    # langgraph-checkpoint-postgres (migration 0009)
    "checkpoints",
    "checkpoint_blobs",
    "checkpoint_writes",
    "checkpoint_migrations",
}


@pytest.fixture
def fresh_db_url(postgres_url: str) -> Iterator[str]:
    """An empty database of its own, so going down and up does not disturb other tests."""
    name = "hub_migration_test"
    with psycopg.connect(libpq_url(postgres_url), autocommit=True) as connection:
        connection.execute(sql.SQL("DROP DATABASE IF EXISTS {}").format(sql.Identifier(name)))
        connection.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(name)))
    url = as_user(postgres_url, "hub", "hub", database=name)
    yield url
    with psycopg.connect(libpq_url(postgres_url), autocommit=True) as connection:
        connection.execute(sql.SQL("DROP DATABASE {} WITH (FORCE)").format(sql.Identifier(name)))


def _tables(url: str) -> set[str]:
    with psycopg.connect(libpq_url(url)) as connection:
        rows = connection.execute(
            "SELECT tablename FROM pg_tables WHERE schemaname = 'public'"
        ).fetchall()
    return {row[0] for row in rows} - {"alembic_version"}


def test_upgrade_downgrade_upgrade(fresh_db_url: str) -> None:
    migrate(fresh_db_url)
    assert _tables(fresh_db_url) == TABLES

    command.downgrade(alembic_config(fresh_db_url), "base")
    assert _tables(fresh_db_url) == set()

    migrate(fresh_db_url)
    assert _tables(fresh_db_url) == TABLES


def test_migrated_schema_matches_the_models(fresh_db_url: str) -> None:
    migrate(fresh_db_url)
    # Raises AutoGenerateDiffsDetected when autogenerate would write any operation. Covers
    # tables, columns, types, nullability, server defaults (env.py turns that on), indexes,
    # unique and foreign keys; not CHECKs.
    command.check(alembic_config(fresh_db_url))


def test_tables_created_by_later_migrations_get_the_app_privileges(fresh_db_url: str) -> None:
    # The default privileges of migration 0001 cover tables that do not exist yet.
    migrate(fresh_db_url)
    with psycopg.connect(libpq_url(fresh_db_url)) as connection:
        connection.execute("CREATE TABLE later_table (id bigserial PRIMARY KEY)")
        # One privilege per call: with a list, has_table_privilege is true when ANY is held.
        row = connection.execute(
            "SELECT bool_and(has_table_privilege('hub_app', 'later_table', p)),"
            " has_sequence_privilege('hub_app', 'later_table_id_seq', 'USAGE')"
            " FROM unnest(ARRAY['SELECT', 'INSERT', 'UPDATE', 'DELETE']) AS p"
        ).fetchone()
        connection.rollback()
    assert row == (True, True)


def test_the_app_role_reads_and_writes_the_checkpoint_tables_but_owns_none(
    fresh_db_url: str,
) -> None:
    # Migration 0009 creates them as the migrator; the app role gets DML from the default
    # privileges of 0001 and never DDL (the checkpointer's `setup()` never runs in the app).
    migrate(fresh_db_url)
    with psycopg.connect(libpq_url(fresh_db_url)) as connection:
        rows = connection.execute(
            "SELECT tablename, tableowner,"
            " bool_and(has_table_privilege('hub_app', tablename, p))"
            " FROM pg_tables, unnest(ARRAY['SELECT', 'INSERT', 'UPDATE', 'DELETE']) AS p"
            " WHERE tablename LIKE 'checkpoint%' GROUP BY tablename, tableowner ORDER BY 1"
        ).fetchall()
        migrations = connection.execute("SELECT count(*) FROM checkpoint_migrations").fetchone()
    assert [name for name, _, _ in rows] == sorted(
        ["checkpoints", "checkpoint_blobs", "checkpoint_writes", "checkpoint_migrations"]
    )
    assert all(owner == "hub" and allowed for _, owner, allowed in rows)
    from langgraph.checkpoint.postgres.base import BasePostgresSaver

    # Like `setup()`: one row per step, 0 included.
    assert migrations == (10,)
    # 0009 is frozen at the 3.2.0 steps; a library with more needs a new migration.
    assert len(BasePostgresSaver.MIGRATIONS) == 10


def test_there_is_exactly_one_head() -> None:
    from alembic.script import ScriptDirectory

    heads = ScriptDirectory.from_config(alembic_config("postgresql://unused")).get_heads()
    assert heads == ["0014"]
