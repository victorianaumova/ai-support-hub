// Writes src/components/icons.generated.ts from the pinned @material-symbols/svg-400 package
// (Apache-2.0). Only the path data of the icons listed here ships; no icon font, no runtime
// dependency. Run after changing the list: `node scripts/icons.mjs`.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const NAMES = [
  "add", "arrow_forward", "chat", "check_circle", "description", "error", "flag", "history",
  "hourglass_top", "inbox", "info", "lock", "logout", "menu_book", "monitoring", "person",
  "refresh", "schedule", "search", "send", "settings", "smart_toy", "support_agent",
  "thumb_down", "thumb_up", "verified_user", "warning",
];

const require = createRequire(import.meta.url);
const root = dirname(require.resolve("@material-symbols/svg-400/package.json"));
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const lines = NAMES.map((name) => {
  const svg = readFileSync(join(root, "outlined", `${name}.svg`), "utf8");
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1) throw new Error(`${name}: expected one path, found ${paths.length}`);
  return `  ${name}: "${paths[0]}",`;
});
const out = `// Generated by scripts/icons.mjs from @material-symbols/svg-400@${version} (outlined, Apache-2.0).
// Do not edit by hand.
export const ICONS = {
${lines.join("\n")}
} as const;

export type IconName = keyof typeof ICONS;
`;
writeFileSync(new URL("../src/components/icons.generated.ts", import.meta.url), out);
console.log(`${NAMES.length} icons written`);
